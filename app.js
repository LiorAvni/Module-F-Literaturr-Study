function route() {
  const hash = location.hash || "#/home";
  const parts = hash.replace(/^#\/?/, "").split("/");
  if (parts[0] === "piece") routes.piece(parts[1], parts[2]);
  else if (parts[0] === "strategy") routes.strategy();
  else routes.home();
  setActiveNav();
  closeMobileNav();
  setTimeout(() => {
    if (location.hash.includes("#q-")) return;
    document.querySelector(".main").scrollTo?.(0,0);
    window.scrollTo(0,0);
  }, 0);
}

function buildSearchIndex() {
  const index = [];
  Object.entries(pieces).forEach(([slug, piece]) => {
    index.push({title: piece.title, type: "Piece", url: `#/piece/${slug}/summary`, text: `${piece.title} ${piece.author} ${piece.short}`});
    index.push({title: `${piece.title}: Overview`, type: "Summary", url: `#/piece/${slug}/summary#overview`, text: piece.summary.overview});
    ["plot", "characters", "themes", "symbols", "examTips"].forEach(key => {
      const value = piece.summary[key];
      const label = {plot:"Plot timeline", characters:"Characters", themes:"Themes", symbols:"Symbols", examTips:"Exam tips"}[key];
      const text = Array.isArray(value) ? value.flat(2).join(" ") : String(value);
      index.push({title: `${piece.title}: ${label}`, type: "Analysis", url: `#/piece/${slug}/summary#${slugify(label)}`, text});
    });
    piece.questions.forEach((item, i) => index.push({title: `${piece.title}: Question ${i+1}`, type: "Question", url: `#/piece/${slug}/questions#q-${i+1}`, text: `${item.q} ${item.e.join(" ")}`}));
    if (piece.text) index.push({title: `${piece.title}: Original text`, type: "Text", url: `#/piece/${slug}/text`, text: piece.text});
  });
  strategyContent.blocks.forEach(([h,p],i) => index.push({title: h, type:"Strategy", url:`#/strategy#strategy-${i+1}`, text:p}));
  return index;
}

const searchIndex = buildSearchIndex();

function doSearch(query) {
  const q = query.trim().toLowerCase();
  if (!q) { searchResults.hidden = true; searchResults.innerHTML = ""; return; }
  const words = q.split(/\s+/).filter(Boolean);
  const results = searchIndex.map(item => {
    const hay = `${item.title} ${item.text}`.toLowerCase();
    const score = words.reduce((acc, w) => acc + (hay.includes(w) ? 1 : 0), 0) + (item.title.toLowerCase().includes(q) ? 3 : 0);
    return {...item, score};
  }).filter(r => r.score > 0).sort((a,b) => b.score - a.score).slice(0, 12);

  searchResults.hidden = false;
  searchResults.innerHTML = `<h2>Search results</h2>${results.length ? results.map(r => `
    <a class="result-item" href="${r.url}"><strong>${escapeHtml(r.title)}</strong><span>${r.type} - ${escapeHtml(snippet(r.text, q))}</span></a>
  `).join("") : `<div class="notice">No results found for <strong>${escapeHtml(query)}</strong>.</div>`}`;
}

function snippet(text, q) {
  const clean = String(text).replace(/\s+/g, " ");
  const idx = clean.toLowerCase().indexOf(q.toLowerCase());
  if (idx === -1) return clean.slice(0, 150) + (clean.length > 150 ? "..." : "");
  return (idx > 40 ? "..." : "") + clean.slice(Math.max(0, idx - 40), idx + 120) + "...";
}

