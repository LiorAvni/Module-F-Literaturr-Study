function route() {
  const parts = getRouteParts();
  const anchor = parts[3];
  if (parts[0] === "piece") renderPiece(parts[1], parts[2] || "summary", anchor);
  else if (parts[0] === "strategy") renderStrategy();
  else renderHome();
  setActiveNav(); closeMobileNav();
  setTimeout(() => {
    if (anchor) {
      const el = document.getElementById(anchor);
      if (el) { if (el.tagName.toLowerCase() === "details") el.open = true; el.scrollIntoView({behavior:"smooth", block:"start"}); return; }
    }
    window.scrollTo({top:0, behavior:"auto"});
  }, 30);
}
function buildSearchIndex() {
  const index = [];
  Object.entries(pieces).forEach(([slug, piece]) => {
    index.push({title: piece.title, type:"Piece", url:makeUrl(slug,"summary"), text:`${piece.title} ${piece.author} ${piece.short}`});
    index.push({title:`${piece.title}: Overview`, type:"Summary", url:makeUrl(slug,"summary","overview"), text:piece.summary.overview});
    const groups = {"plot":"Plot timeline", "characters":"Characters", "themes":"Themes", "symbols":"Symbols and motifs", "deepAnalysis":"Deep analysis", "questionAnalysis":"Question-pool integrated analysis", "examTips":"Exam tips"};
    Object.entries(groups).forEach(([key,label]) => {
      const value = piece.summary[key]; const text = Array.isArray(value) ? value.flat(2).join(" ") : String(value);
      index.push({title:`${piece.title}: ${label}`, type:"Analysis", url:makeUrl(slug,"summary",slugify(label)), text});
    });
    piece.questions.forEach((item, i) => index.push({title:`${piece.title}: Question ${i+1}`, type:"Question", url:makeUrl(slug,"questions",`q-${i+1}`), text:`${item.q} ${item.e.join(" ")}`}));
    if (piece.text) index.push({title:`${piece.title}: Original text`, type:"Text", url:makeUrl(slug,"text"), text:piece.text});
  });
  strategyContent.blocks.forEach(([h,p],i) => index.push({title:h, type:"Strategy", url:`#/strategy/${`strategy-${i+1}`}`, text:p}));
  return index;
}
const searchIndex = buildSearchIndex();
function hideSuggestions(){ suggestions.hidden = true; suggestions.innerHTML = ""; }
function doSearch(query) {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return hideSuggestions();
  const words = q.split(/\s+/).filter(Boolean);
  const results = searchIndex.map(item => {
    const hay = `${item.title} ${item.text}`.toLowerCase();
    let score = 0;
    if (item.title.toLowerCase().includes(q)) score += 8;
    words.forEach(w => { if (hay.includes(w)) score += 1; if (item.title.toLowerCase().includes(w)) score += 2; });
    return {...item, score};
  }).filter(r => r.score > 0).sort((a,b) => b.score - a.score).slice(0, 8);
  if (!results.length) return hideSuggestions();
  suggestions.hidden = false;
  suggestions.innerHTML = results.map(r => `<button class="suggestion-item" type="button" data-url="${r.url}"><strong>${escapeHtml(r.title)}</strong><span>${escapeHtml(r.type)} - ${escapeHtml(snippet(r.text, q))}</span></button>`).join("");
}
function snippet(text, q) {
  const clean = String(text).replace(/\s+/g, " "); const idx = clean.toLowerCase().indexOf(q.toLowerCase());
  if (idx === -1) return clean.slice(0, 100) + (clean.length > 100 ? "..." : "");
  return (idx > 28 ? "..." : "") + clean.slice(Math.max(0, idx-28), idx+90) + "...";
}
